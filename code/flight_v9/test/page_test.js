// 开发用：在 node 里用桩对象跑网页脚本，喂一帧与固件 web_build_json 同格式的遥测，检查解析 / 显示 / 按钮逻辑
const fs = require('fs');
const html = fs.readFileSync(__dirname + '/../main/web/index.html', 'utf8');
const i0 = html.indexOf('<script>') + 8, i1 = html.lastIndexOf('</' + 'script>');
const js = html.slice(i0, i1);
const els = {};
const mk = id => (els[id] = els[id] || { id, textContent: '', innerHTML: '', disabled: false, style: {}, dataset: {}, handlers: {},
  addEventListener(n, f) { (this.handlers[n] = this.handlers[n] || []).push(f); }, querySelector() { return { style: {} }; } });
const sent = [];
let wsInst = null;
global.document = { getElementById: mk, querySelectorAll: () => [], addEventListener() {}, hidden: false };
global.location = { host: '192.168.4.1' };
global.performance = { now: () => Date.now() };
global.navigator = {};
global.requestAnimationFrame = () => 0; global.cancelAnimationFrame = () => {};
const intervals = [];
global.setInterval = (f, t) => intervals.push(f);
global.setTimeout = (f, t) => f();
global.WebSocket = class { constructor(u) { this.url = u; this.readyState = 1; wsInst = this; } send(t) { sent.push(t); } close() {} };
eval(js);
let ok = true;
const check = (c, msg) => { console.log((c ? '  ✓ ' : '  ✗ ') + msg); ok = ok && c; };
check(wsInst && wsInst.url === 'ws://192.168.4.1/ws', '连接 ws://192.168.4.1/ws');
intervals[0](); intervals[0]();
check(sent[0] === 'hb 1' && sent[1] === 'hb 2', '心跳格式 hb <seq>：' + sent.slice(0, 2).join(' / '));
const frame = (st, ts, evs, evl) => ({ data: `{"st":${st},"ts":${ts},"mode":0,"r":-0.1,"p":-0.3,"y":2.0,"z":0.01,"vz":-0.02,"zt":0.00,` +
  `"vb":4.17,"k":1.97,"u":[0.741,0.750,0.752,0.744],"out":0.000,"mo":0,"lk":1,"hb":2,"gap":105,"evs":${evs},"ev":"${evl.length ? evl[evl.length - 1][1] : ''}","evl":${JSON.stringify(evl)}}` });
wsInst.onmessage(frame(0, 3.2, 0, []));
check(els.st.textContent === '未解锁', '状态显示：' + els.st.textContent);
check(els.vb.textContent === '4.17 V', '电压：' + els.vb.textContent);
check(els.arm.disabled === false && els.tko.disabled === true && els.land.disabled === true, '未解锁时：只有「解锁」可按');
check(els.mo.textContent.indexOf('干跑') >= 0, '干跑提示：' + els.mo.textContent);
wsInst.onmessage(frame(1, 4.0, 1, [[1, 'armed']]));
check(els.st.textContent === '已解锁' && els.arm.disabled && !els.tko.disabled, '已解锁：「起飞」可按，「解锁」不可按');
check(els.hint.textContent.indexOf('16 秒后自动上锁') >= 0, '已解锁提示倒计时：' + els.hint.textContent);
check(els.log.innerHTML.indexOf('已解锁') >= 0, '事件日志记录「已解锁」');
wsInst.onmessage(frame(4, 2.0, 3, [[1, 'armed'], [2, 'takeoff'], [3, 'stable_hold']]));
check(els.hint.textContent.indexOf('3.0 秒后自动降落') >= 0, '悬停提示倒计时：' + els.hint.textContent);
check(els.log.innerHTML.indexOf('起飞') >= 0 && els.log.innerHTML.indexOf('已稳定') >= 0, '一帧里多个新事件都记进日志');
check(!els.land.disabled, '悬停时「降落」可按');
sent.length = 0;
els.kill.handlers.pointerdown[0]({ preventDefault() {} });
check(sent.filter(x => x === 'cmd disarm').length === 3, '急停：按下立即发 3 次 cmd disarm');
sent.length = 0;
els.land.handlers.pointerdown[0]({ preventDefault() {} });
check(sent[0] === 'cmd land', '降落：发 cmd land');
wsInst.onmessage(frame(5, 1.0, 5, [[4, 'land_auto'], [5, 'landed']]));
check(els.log.innerHTML.indexOf('自动降落') >= 0 && els.log.innerHTML.indexOf('触地') >= 0, '降落 / 触地事件');
const mframe = (extra) => ({ data: frame(0, 1.0, 5, [[5, 'landed']]).data.replace('"mo":0,', '"mo":1,' + extra) });
wsInst.onmessage(mframe('"um":0.060,"mk":0,'));
check(els.mo.textContent.indexOf('电机会真转') >= 0 && els.mo.textContent.indexOf('6%') >= 0, '电机驱动版提示油门上限：' + els.mo.textContent);
wsInst.onmessage(mframe('"um":0.060,"mk":1,'));
check(els.mo.textContent.indexOf('看门狗') >= 0, '看门狗锁死提示：' + els.mo.textContent);
console.log(ok ? '网页脚本测试全部通过' : '有失败项');
process.exit(ok ? 0 : 1);
